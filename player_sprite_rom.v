module player_sprite_rom (
    input  wire [11:0] address,

    output reg         transparent,
    output reg  [3:0]  red,
    output reg  [3:0]  green,
    output reg  [3:0]  blue
);

    reg [5:0] x;
    reg [4:0] y;

    always @(*) begin

        x = address[5:0];
        y = address[10:6];

        transparent = 1'b1;

        red   = 4'd0;
        green = 4'd0;
        blue  = 4'd0;


        //================================================
        // Engine flame outer glow
        //================================================

        if (
            (x >= 2)  &&
            (x <= 13) &&
            (y >= 13) &&
            (y <= 18)
        ) begin
            transparent = 1'b0;

            red   = 4'd15;
            green = 4'd3;
            blue  = 4'd1;
        end


        //================================================
        // Engine flame inner core
        //================================================

        if (
            (x >= 6)  &&
            (x <= 16) &&
            (y >= 14) &&
            (y <= 17)
        ) begin
            transparent = 1'b0;

            red   = 4'd15;
            green = 4'd12;
            blue  = 4'd2;
        end


        //================================================
        // Lower wing
        //================================================

        if (
            (x >= 17) &&
            (x <= 45) &&
            (y >= 20) &&
            (y <= 27) &&
            ((x + y) <= 67)
        ) begin
            transparent = 1'b0;

            red   = 4'd1;
            green = 4'd8;
            blue  = 4'd12;
        end


        //================================================
        // Upper wing
        //================================================

        if (
            (x >= 17) &&
            (x <= 45) &&
            (y >= 4)  &&
            (y <= 11) &&
            ((x - y) <= 37)
        ) begin
            transparent = 1'b0;

            red   = 4'd1;
            green = 4'd8;
            blue  = 4'd12;
        end


        //================================================
        // Rear engine body
        //================================================

        if (
            (x >= 12) &&
            (x <= 25) &&
            (y >= 11) &&
            (y <= 20)
        ) begin
            transparent = 1'b0;

            red   = 4'd2;
            green = 4'd5;
            blue  = 4'd9;
        end


        //================================================
        // Main aircraft body
        //================================================

        if (
            (x >= 20) &&
            (x <= 55) &&
            (y >= 10) &&
            (y <= 21)
        ) begin
            transparent = 1'b0;

            red   = 4'd2;
            green = 4'd12;
            blue  = 4'd15;
        end


        //================================================
        // Nose cone
        //================================================

        if (
            (x >= 55) &&
            (x <= 62) &&
            (y >= 13) &&
            (y <= 18)
        ) begin
            transparent = 1'b0;

            red   = 4'd6;
            green = 4'd15;
            blue  = 4'd15;
        end


        //================================================
        // Nose taper
        //================================================

        if (
            (x >= 58) &&
            (x <= 63) &&
            (y >= 14) &&
            (y <= 17)
        ) begin
            transparent = 1'b0;

            red   = 4'd12;
            green = 4'd15;
            blue  = 4'd15;
        end


        //================================================
        // Cockpit frame
        //================================================

        if (
            (x >= 36) &&
            (x <= 48) &&
            (y >= 8)  &&
            (y <= 14)
        ) begin
            transparent = 1'b0;

            red   = 4'd1;
            green = 4'd3;
            blue  = 4'd7;
        end


        //================================================
        // Cockpit glass
        //================================================

        if (
            (x >= 39) &&
            (x <= 47) &&
            (y >= 9)  &&
            (y <= 12)
        ) begin
            transparent = 1'b0;

            red   = 4'd4;
            green = 4'd14;
            blue  = 4'd15;
        end


        //================================================
        // Bright hull highlight
        //================================================

        if (
            (x >= 24) &&
            (x <= 54) &&
            (y >= 10) &&
            (y <= 12)
        ) begin
            transparent = 1'b0;

            red   = 4'd10;
            green = 4'd15;
            blue  = 4'd15;
        end


        //================================================
        // Dark underside
        //================================================

        if (
            (x >= 24) &&
            (x <= 54) &&
            (y >= 19) &&
            (y <= 21)
        ) begin
            transparent = 1'b0;

            red   = 4'd0;
            green = 4'd5;
            blue  = 4'd10;
        end


        //================================================
        // Wing neon accents
        //================================================

        if (
            (x >= 21) &&
            (x <= 38) &&
            ((y == 6) || (y == 25))
        ) begin
            transparent = 1'b0;

            red   = 4'd3;
            green = 4'd15;
            blue  = 4'd15;
        end


        //================================================
        // Engine light
        //================================================

        if (
            (x >= 13) &&
            (x <= 18) &&
            (y >= 13) &&
            (y <= 18)
        ) begin
            transparent = 1'b0;

            red   = 4'd2;
            green = 4'd15;
            blue  = 4'd15;
        end

    end

endmodule