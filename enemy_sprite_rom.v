module enemy_sprite_rom (
    input  wire [11:0] address,

    output reg         transparent,
    output reg  [3:0]  red,
    output reg  [3:0]  green,
    output reg  [3:0]  blue
);

    reg [5:0] x;
    reg [4:0] y;

    always @(*) begin

        x = address[5:0];
        y = address[10:6];

        transparent = 1'b1;

        red   = 4'd0;
        green = 4'd0;
        blue  = 4'd0;


        //================================================
        // Upper blade
        //================================================

        if (
            (x >= 16) &&
            (x <= 47) &&
            (y >= 4)  &&
            (y <= 10) &&
            ((x + y) >= 24) &&
            ((x - y) <= 40)
        ) begin
            transparent = 1'b0;

            red   = 4'd9;
            green = 4'd2;
            blue  = 4'd1;
        end


        //================================================
        // Lower blade
        //================================================

        if (
            (x >= 16) &&
            (x <= 47) &&
            (y >= 21) &&
            (y <= 27) &&
            ((x - y) >= -11) &&
            ((x + y) <= 72)
        ) begin
            transparent = 1'b0;

            red   = 4'd9;
            green = 4'd2;
            blue  = 4'd1;
        end


        //================================================
        // Left armor section
        //================================================

        if (
            (x >= 8)  &&
            (x <= 25) &&
            (y >= 11) &&
            (y <= 20)
        ) begin
            transparent = 1'b0;

            red   = 4'd6;
            green = 4'd1;
            blue  = 4'd2;
        end


        //================================================
        // Main armored body
        //================================================

        if (
            (x >= 20) &&
            (x <= 50) &&
            (y >= 9)  &&
            (y <= 22)
        ) begin
            transparent = 1'b0;

            red   = 4'd12;
            green = 4'd3;
            blue  = 4'd1;
        end


        //================================================
        // Front spike
        //================================================

        if (
            (x >= 49) &&
            (x <= 62) &&
            (y >= 13) &&
            (y <= 18)
        ) begin
            transparent = 1'b0;

            red   = 4'd15;
            green = 4'd5;
            blue  = 4'd1;
        end


        //================================================
        // Dark metal panel
        //================================================

        if (
            (x >= 26) &&
            (x <= 44) &&
            (y >= 11) &&
            (y <= 20)
        ) begin
            transparent = 1'b0;

            red   = 4'd3;
            green = 4'd1;
            blue  = 4'd3;
        end


        //================================================
        // Glowing energy core
        //================================================

        if (
            (x >= 31) &&
            (x <= 39) &&
            (y >= 12) &&
            (y <= 19)
        ) begin
            transparent = 1'b0;

            red   = 4'd15;
            green = 4'd8;
            blue  = 4'd1;
        end


        //================================================
        // Core center
        //================================================

        if (
            (x >= 33) &&
            (x <= 37) &&
            (y >= 14) &&
            (y <= 17)
        ) begin
            transparent = 1'b0;

            red   = 4'd15;
            green = 4'd15;
            blue  = 4'd5;
        end


        //================================================
        // Upper armor highlight
        //================================================

        if (
            (x >= 22) &&
            (x <= 48) &&
            (y >= 9)  &&
            (y <= 10)
        ) begin
            transparent = 1'b0;

            red   = 4'd15;
            green = 4'd7;
            blue  = 4'd2;
        end


        //================================================
        // Lower armor shadow
        //================================================

        if (
            (x >= 22) &&
            (x <= 48) &&
            (y >= 21) &&
            (y <= 22)
        ) begin
            transparent = 1'b0;

            red   = 4'd5;
            green = 4'd0;
            blue  = 4'd2;
        end


        //================================================
        // Rear thruster
        //================================================

        if (
            (x >= 5)  &&
            (x <= 11) &&
            (y >= 14) &&
            (y <= 17)
        ) begin
            transparent = 1'b0;

            red   = 4'd15;
            green = 4'd2;
            blue  = 4'd8;
        end

    end

endmodule